// Tester: ticket #516 — every session in the /resume and /sessions listing must
// carry a NAME, and deriving that name must NEVER read a whole session file.
// Runs on every push via .github/workflows/per-service-tests.yml (registered in
// build.json tests.resume-session-names, cwd=src/code).
//
// Diego's report was "add the namee!!!!!!" under a listing of 40 bare UUIDs,
// half of them written inside the same 60 seconds so the timestamp did not tell
// them apart either. The two checks that matter are therefore:
//
//   CHECK 1 (named)   — every row served by /sessions has a non-empty name, and
//                       the name is never just the UUID echoed back.
//   CHECK 2 (bounded) — naming a 100 MB+ session reads only a bounded number of
//                       bytes. This is not a style preference: /sessions walks
//                       every device directory on every call and the live store
//                       holds a 127,487,011-byte transcript, so a namer that
//                       reads files is an OOM on exactly the sessions Diego most
//                       wants to resume.
//
// Both are mutation-proven: strip the name field from server.mjs's row -> CHECK 1
// red; make deriveSessionName read the whole file (drop the byte bound) ->
// CHECK 2 red. See the ticket report for the pasted runs.
//
// CHECK 2 is instrumented rather than asserted by eye: it monkey-patches
// fs.readSync/readFileSync to COUNT the bytes deriveSessionName actually pulls,
// so it fails on real I/O rather than on a promise in a comment.
//
// REAL-FILE ANCHOR. Checks 4-6 run against the REAL store at
// /home/appuser/.goose-sessions (20 localhost + 20 surface-nixos sessions in the
// my-ai-api container), including the 121.6 MB
// localhost/6f096941-091d-4b8f-a3bd-03c6f7bc8287.jsonl that the byte bound
// exists because of. A fixture in a format we chose would prove nothing about a
// format upstream chose. That path does not exist on a CI runner, so those checks
// SKIP loudly there and are run by hand in the container (pasted in the report);
// checks 1-3 and 7-9 are self-contained and run everywhere.
//
// Usage: node test-my-ai-resume-session-names.mjs   (exit 0 = PASS)
import fs from "node:fs";
import { mkdtempSync, mkdirSync, writeFileSync, existsSync, statSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, basename } from "node:path";

const TMP = mkdtempSync(join(tmpdir(), "myai-names-516-"));
process.env.BRIDGE_SESSIONS_DIR = TMP;
process.env.BRIDGE_RESUME_MAX_LISTED = "40";
// Deliberately SMALL windows so the bound is exercised rather than asserted
// against a limit nothing reaches.
process.env.BRIDGE_NAME_HEAD_BYTES = "8192";
process.env.BRIDGE_NAME_TAIL_BYTES = "4096";
process.env.BRIDGE_NAME_MAX_CHARS = "60";

const store = await import(new URL("./sessions-store.mjs", import.meta.url).href);

const failures = [];
const skips = [];
const ok = (l) => console.log(`  OK: ${l}`);
const bad = (l) => { failures.push(l); console.log(`FAIL: ${l}`); };
const skip = (l) => { skips.push(l); console.log(`SKIP: ${l}`); };
const check = (cond, label) => (cond ? ok(label) : bad(label));

// ── fixture store: the two on-disk shapes this module owns ──────────────────
// Claude Code shape. The records are the real ones: a custom-title, the
// leafUuid-only last-prompt that opens most real files (NO text in it — naming
// must not mistake it for a label), a caveat-wrapped injected turn, and a
// last-prompt carrying the actual prompt at the END.
const titled = [
  `{"type":"custom-title","customTitle":"cloud-mail","sessionId":"aaaa1111-0000-0000-0000-000000000001"}`,
  `{"type":"mode","mode":"normal","sessionId":"aaaa1111-0000-0000-0000-000000000001"}`,
  `{"type":"user","message":{"role":"user","content":[{"type":"text","text":"first thing typed"}]}}`,
  `{"type":"last-prompt","lastPrompt":"the newest prompt","sessionId":"aaaa1111-0000-0000-0000-000000000001"}`,
].join("\n");

// No title: the name must come from the LAST last-prompt in the tail, not the
// first, and not from the caveat-wrapped pseudo-turn at the head.
const prompted = [
  `{"type":"last-prompt","leafUuid":"93f99602-d4a2-44db-898e-278eb2fca95e","sessionId":"bbbb2222-0000-0000-0000-000000000002"}`,
  `{"type":"user","message":{"role":"user","content":[{"type":"text","text":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to them.</local-command-caveat>"}]}}`,
  `{"type":"last-prompt","lastPrompt":"an older prompt","sessionId":"bbbb2222-0000-0000-0000-000000000002"}`,
  `{"type":"last-prompt","lastPrompt":"check why sshd alias not working","sessionId":"bbbb2222-0000-0000-0000-000000000002"}`,
].join("\n");

// The bot's OWN flat {role,content} NDJSON (what saveTelegramHistory writes).
// It has neither a custom-title nor a last-prompt, so it MUST be named by the
// first-message rung — otherwise every telegram chat lists as "(unnamed)".
const flat = store.serializeHistory([
  { role: "user", content: "add the namee!!!!!!" },
  { role: "assistant", content: "on it" },
]);

// Nothing nameable at all: the 146-byte bridge-session stub in the real store.
const stub = `{"type":"bridge-session","sessionId":"dddd4444-0000-0000-0000-000000000004","bridgeSessionId":"cse_01DFoLot9GiUSTwA4UVPfCtC","lastSequenceNum":0}`;

// Records carrying a cwd but no prompt -> the honest cwd fallback.
const cwdOnly = [
  `{"type":"last-prompt","leafUuid":"66e2bac6-beee-406c-8ce0-99c462c4b4a0","sessionId":"eeee5555-0000-0000-0000-000000000005"}`,
  `{"type":"mode","mode":"normal","cwd":"/data/data/com.termux.nix/files/home","sessionId":"eeee5555-0000-0000-0000-000000000005"}`,
].join("\n");

const write = (device, id, body) => {
  const d = join(TMP, device);
  mkdirSync(d, { recursive: true });
  const f = join(d, `${id}.jsonl`);
  writeFileSync(f, `${body}\n`);
  return f;
};
const F_TITLED = write("localhost", "aaaa1111-0000-0000-0000-000000000001", titled);
const F_PROMPT = write("localhost", "bbbb2222-0000-0000-0000-000000000002", prompted);
const F_FLAT = write("telegram", "cccc3333-0000-0000-0000-000000000003", flat);
const F_STUB = write("localhost", "dddd4444-0000-0000-0000-000000000004", stub);
const F_CWD = write("surface-nixos", "eeee5555-0000-0000-0000-000000000005", cwdOnly);

// ── the /sessions listing, built by the REAL server code ────────────────────
// server.mjs is imported rather than reimplemented: the point of the ticket is
// that the name is served from ONE place, so the tester must assert the thing
// that place actually returns. It binds a port, so use an unused one.
process.env.BRIDGE_PORT = "13917";
process.env.BRIDGE_BIND = "127.0.0.1";
process.env.BRIDGE_OLLAMA_PORT = "13918";
process.env.MCP_ENABLED = "0";
process.env.MYAI_LOCAL_URL = "http://127.0.0.1:13917";
await import(new URL("./server.mjs", import.meta.url).href);
const listing = await fetch("http://127.0.0.1:13917/sessions").then((r) => r.json());

// ── 1. EVERY listed session has a name (the ticket, in one assertion) ───────
const unnamed = listing.filter((s) => !s.name || !String(s.name).trim());
check(listing.length === 5 && unnamed.length === 0,
  `every one of the ${listing.length} listed sessions has a non-empty name` +
  (unnamed.length ? ` — MISSING on: ${unnamed.map((s) => s.id).join(", ")}` : ""));

// A name equal to the id would satisfy "non-empty" while telling Diego nothing —
// the ticket explicitly forbids the UUID silently standing in as a name.
const idAsName = listing.filter((s) => s.name === s.id);
check(idAsName.length === 0,
  `no row uses its own UUID as its name${idAsName.length ? ` — ${idAsName.map((s) => s.id).join(", ")}` : ""}`);

// ── 2. each rung produces the right name, and says which rung it was ────────
const byId = Object.fromEntries(listing.map((s) => [s.id, s]));
const t = byId["aaaa1111-0000-0000-0000-000000000001"];
check(t.name === "cloud-mail" && t.name_from === "title",
  `a session Diego titled is named by his title, not by its content — got ${JSON.stringify(t.name)} via ${t.name_from}`);

const p = byId["bbbb2222-0000-0000-0000-000000000002"];
check(p.name === "check why sshd alias not working" && p.name_from === "last-prompt",
  `an untitled session is named by its NEWEST last-prompt — got ${JSON.stringify(p.name)} via ${p.name_from}`);

const fl = byId["cccc3333-0000-0000-0000-000000000003"];
check(fl.name === "add the namee!!!!!!" && fl.name_from === "first-message",
  `the bot's own flat {role,content} NDJSON is named too — got ${JSON.stringify(fl.name)} via ${fl.name_from}`);

const c = byId["eeee5555-0000-0000-0000-000000000005"];
check(c.name_from === "cwd" && c.name.startsWith("home") && c.name !== "",
  `no prompt anywhere -> honest cwd fallback, visibly marked — got ${JSON.stringify(c.name)} via ${c.name_from}`);

const st = byId["dddd4444-0000-0000-0000-000000000004"];
check(st.name === "(unnamed)" && st.name_from === "none",
  `a stub with nothing nameable says so instead of going blank — got ${JSON.stringify(st.name)} via ${st.name_from}`);

// A caveat-wrapped injected turn must never become the name: 19 of the 40 real
// sessions open with one, so naming from it gives a dozen rows one useless label.
check(!listing.some((s) => String(s.name).includes("local-command-caveat")),
  "a machine-injected <local-command-caveat> turn is never used as a name");

// ── 3. the name reaches the BOT through the endpoint, not a second reader ───
// commands.mjs must format what /sessions served. Both Telegram bots (goose and
// claude, per bots.json) call this same handleCommand, so this covers both.
const cmds = await import(new URL("./bots/commands.mjs", import.meta.url).href);
const reply = await cmds.handleCommand("resume", "", "telegram-claude:516", {}, "claude");
check(reply.includes("cloud-mail") && reply.includes("check why sshd alias not working") &&
      reply.includes("add the namee!!!!!!"),
  "/resume's listing renders the served names (the bot formats, it does not re-read the store)");
check(reply.includes("aaaa1111-0000-0000-0000-000000000001"),
  "/resume's listing still carries the id, so /resume <id> is still typable");

// /sessions must show the SAME names — a /sessions that listed bare UUIDs while
// /resume showed names would be the old bug wearing the other command's name.
const sessReply = await cmds.handleCommand("sessions", "", "telegram-claude:516", {}, "claude");
check(sessReply.includes("cloud-mail") && sessReply.includes("check why sshd alias not working"),
  "/sessions shows the same names as /resume (one shared row renderer)");
const searched = await cmds.handleCommand("sessions", "search cloud-mail", "telegram-claude:516", {}, "claude");
check(searched.includes("cloud-mail") && !searched.includes("no matches"),
  "/sessions search matches a NAME, not only a UUID");

// ── 4. REAL STORE: every real session gets a name ──────────────────────────
const REAL_DIR = "/home/appuser/.goose-sessions";
const REAL_BIG = join(REAL_DIR, "localhost", "6f096941-091d-4b8f-a3bd-03c6f7bc8287.jsonl");
if (!existsSync(REAL_DIR)) {
  skip(`real store ${REAL_DIR} not present (expected on a CI runner) — real-store checks 4-6 not run`);
} else {
  const real = [];
  for (const dev of readdirSync(REAL_DIR)) {
    const dd = join(REAL_DIR, dev);
    if (!statSync(dd).isDirectory()) continue;
    for (const f of readdirSync(dd).filter((x) => x.endsWith(".jsonl"))) real.push(join(dd, f));
  }
  const named = real.map((f) => ({ f, ...store.deriveSessionName(f) }));
  const blank = named.filter((n) => !n.name || !n.name.trim());
  check(real.length > 0 && blank.length === 0,
    `all ${real.length} REAL sessions in ${REAL_DIR} get a name` +
    (blank.length ? ` — blank on ${blank.map((b) => basename(b.f)).join(", ")}` : ""));

  // Real names must not be dominated by one useless label: the whole complaint
  // was that Diego could not tell the rows apart.
  const counts = {};
  for (const n of named) counts[n.name] = (counts[n.name] || 0) + 1;
  const worst = Math.max(...Object.values(counts));
  check(worst <= Math.ceil(real.length / 4),
    `no single label swamps the real listing (most-repeated name appears ${worst}x of ${real.length})`);
}

// ── 5+6. REAL 121.6 MB FILE: naming it is BOUNDED ──────────────────────────
// The file the bound exists because of. Counting real bytes read, not trusting
// the code's intent: fs.readSync/readFileSync are wrapped so anything that
// slurps the file is caught.
const countBytes = (fn) => {
  const realReadSync = fs.readSync;
  const realReadFileSync = fs.readFileSync;
  let bytes = 0;
  fs.readSync = (fd, buf, off, len, pos) => { const n = realReadSync(fd, buf, off, len, pos); bytes += n; return n; };
  fs.readFileSync = (...a) => { const r = realReadFileSync(...a); bytes += Buffer.byteLength(r); return r; };
  try { return { result: fn(), bytes }; } finally { fs.readSync = realReadSync; fs.readFileSync = realReadFileSync; }
};

const HEAD = parseInt(process.env.BRIDGE_NAME_HEAD_BYTES, 10);
const TAIL = parseInt(process.env.BRIDGE_NAME_TAIL_BYTES, 10);
const CEILING = HEAD + TAIL;

if (!existsSync(REAL_BIG)) {
  skip(`real 121.6 MB session ${REAL_BIG} not present (expected on a CI runner) — bounded-read check on it not run`);
} else {
  const size = statSync(REAL_BIG).size;
  const { result, bytes } = countBytes(() => store.deriveSessionName(REAL_BIG));
  check(bytes <= CEILING,
    `naming the REAL ${(size / 1048576).toFixed(1)} MB session read ${bytes} bytes, within the ${CEILING}-byte bound ` +
    `(${(size / Math.max(bytes, 1)).toFixed(0)}x less than the file)`);
  check(result.name && result.name.trim() && result.name.length <= 60,
    `...and still produced a usable name for it: ${JSON.stringify(result.name)} (via ${result.name_from ?? result.from})`);
}

// ── 7. the bound holds on a synthetic big file too, so CI proves it as well ──
// CI has no real store, but the bound is the safety property — it must be
// checked SOMEWHERE on every push, not only by hand in the container.
const BIG = join(TMP, "localhost", "ffff6666-0000-0000-0000-000000000006.jsonl");
const filler = `{"type":"attachment","note":"${"x".repeat(900)}"}`;
writeFileSync(BIG,
  `{"type":"user","message":{"role":"user","content":"opening prompt"}}\n` +
  `${new Array(6000).fill(filler).join("\n")}\n` +
  `{"type":"last-prompt","lastPrompt":"the newest prompt in a big file"}\n`);
const bigSize = statSync(BIG).size;
const { result: bigName, bytes: bigBytes } = countBytes(() => store.deriveSessionName(BIG));
check(bigSize > CEILING * 4, `synthetic big file is ${bigSize} bytes, comfortably over the ${CEILING}-byte bound`);
check(bigBytes <= CEILING,
  `naming a ${bigSize}-byte file read only ${bigBytes} bytes (bound ${CEILING}) — a whole-file read would be ${bigSize}`);
check(bigName.name === "the newest prompt in a big file",
  `...and reached the last-prompt at the END of it by seeking, not scanning — got ${JSON.stringify(bigName.name)}`);

// ── 8. row width stays phone-scannable ─────────────────────────────────────
const LONG = join(TMP, "localhost", "ffff7777-0000-0000-0000-000000000007.jsonl");
writeFileSync(LONG, `{"type":"last-prompt","lastPrompt":"${"long prompt ".repeat(40)}"}\n`);
const longName = store.deriveSessionName(LONG);
check(longName.name.length <= 60 && longName.name.endsWith("…"),
  `a long prompt is truncated to the declared width with an ellipsis — ${longName.name.length} chars, got ${JSON.stringify(longName.name)}`);

// ── 9. a label never breaks the row it sits in ─────────────────────────────
// The real store holds a pasted browser error containing a CR and TUI dumps full
// of control characters; one of those unescaped turns a 40-row listing into a
// mess. cleanLabel must flatten them to a single line.
const MESSY = join(TMP, "localhost", "ffff8888-0000-0000-0000-000000000008.jsonl");
writeFileSync(MESSY, `${JSON.stringify({ type: "last-prompt", lastPrompt: "line one\r\nline two\tand[1m bold" })}\n`);
const messy = store.deriveSessionName(MESSY);
check(!/[\r\n\t]/.test(messy.name) && !messy.name.includes(""),
  `a pasted multi-line/ANSI prompt collapses to ONE clean row — got ${JSON.stringify(messy.name)}`);

// ── summary ────────────────────────────────────────────────────────────────
console.log("── tester summary ──");
if (skips.length > 0) console.log(`${skips.length} check(s) skipped:\n${skips.map((s) => `  - ${s}`).join("\n")}`);
if (failures.length > 0) {
  console.error(`RED: ${failures.length} check(s) FAILED:\n${failures.map((f) => `  - ${f}`).join("\n")}`);
  process.exit(1);
}
console.log(`GREEN: all #516 session-naming checks pass${skips.length ? ` (${skips.length} skipped — no real store here)` : ""}`);
process.exit(0);
