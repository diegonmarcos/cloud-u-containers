#!/usr/bin/env node
// Emits _shared/fallback-services.json: the public-safe description of EVERY service declared in
// <service>/build.json (name, description, mesh name, public hosts, how to get in). It is the one
// input of both consumers: the Caddy generator (host -> page slug for the shared 401/403 redirect)
// and the cloud-webapps Pages generator (scripts/gen-fallback.mjs, vendored copy of this file).
// Only declared, already-public facts: no secrets, no IPs. `--check` fails when the committed file is stale.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, '_shared/fallback-services.json');
const PAGES_BASE = 'https://diegonmarcos.github.io/cloud-webapps/';
const strip = s => String(s ?? '').replace(/(\d{1,3}\.){3}\d{1,3}/g, 'a local address').replace(/\s+/g, ' ').trim();

const services = [];
for (const d of readdirSync(root).sort()) {
  const f = join(root, d, 'build.json');
  if (!existsSync(f)) continue;
  const b = JSON.parse(readFileSync(f, 'utf8'));
  if (!b.name) continue;
  const p = b.proxy?.primary ?? {};
  const hosts = [...new Set([p.domain, p.public_host, b.domain].filter(h => typeof h === 'string' && /^[a-z0-9.-]+\.diegonmarcos\.com$/.test(h)))].sort();
  const auth = p.auth ?? null;
  const bearer = auth === 'bearer' || /(-mcp|-api)$/.test(b.name);
  const signin = hosts.length > 0 && !['none', 'bypass', null].includes(auth) && auth !== 'bearer';
  services.push({
    slug: b.name,
    dir: d,
    description: strip(b.description).slice(0, 240),
    mesh: typeof b.dns === 'string' && /^[a-z0-9.-]+\.mesh\.diegonmarcos\.com$/.test(b.dns) ? b.dns : null,
    hosts,
    signin,
    bearer,
  });
}
const slugs = services.map(s => s.slug);
if (new Set(slugs).size !== slugs.length) { console.error('duplicate service names'); process.exit(1); }
const doc = {
  _doc: 'GENERATED by _shared/gen-fallback-services.mjs from <service>/build.json. DO NOT EDIT.',
  pages_base: PAGES_BASE,
  auth_portal: 'https://auth.diegonmarcos.com/',
  account_portal: 'https://account.diegonmarcos.com/',
  providers: ['Authelia', 'Google', 'GitHub', 'Cloudflare'],
  services,
};
const text = JSON.stringify(doc, null, 2) + '\n';
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error('FAIL fallback-services.json is stale: run node _shared/gen-fallback-services.mjs'); process.exit(1); }
  console.log(`ok: fallback-services.json current (${services.length} services)`);
} else { writeFileSync(OUT, text); console.log(`wrote ${services.length} services`); }
