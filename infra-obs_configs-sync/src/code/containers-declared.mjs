#!/usr/bin/env node
// containers-declared.mjs - the ONE derivation of the C3 Containers page data.
// Reads every <service>/build.json of cloud-u-containers plus _shared/containers-taxonomy.json
// and writes containers-declared.json. No dependencies (plain node).
//   node containers-declared.mjs <cloud-u-containers-root> <out-file>
// Canonical home: here (the configs-sync engine). cloud-t-infra 1_cloud-configs only wraps it.
import fs from "node:fs";
import path from "node:path";

export function loadServices(root) {
  return fs.readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory() && fs.existsSync(path.join(root, e.name, "build.json")))
    .map((e) => ({ dir: e.name, b: JSON.parse(fs.readFileSync(path.join(root, e.name, "build.json"), "utf8")) }))
    .sort((a, b) => a.dir.localeCompare(b.dir));
}

// A service's containers: containers{} entries, or the service itself when it ships a compose
// with no containers{} (alerts-api). Everything else (worker, image-only, static site) is an artifact.
export function entriesOf({ dir, b }) {
  const out = [];
  const svcTax = b.taxonomy || null;
  if (b.containers && typeof b.containers === "object") {
    for (const [role, c] of Object.entries(b.containers)) {
      if (!c || typeof c !== "object" || !c.container_name) continue;
      out.push({ kind: "container", name: c.container_name, role, c, tax: c.taxonomy || svcTax });
    }
  } else if (b.compose) {
    out.push({ kind: "container", name: b.name, role: "app", c: {}, tax: svcTax });
  } else {
    out.push({ kind: "artifact", name: b.name, role: "", c: {}, tax: svcTax });
  }
  return out.map((e) => ({ ...e, dir, b }));
}

// Public address of a container: proxy.domain (or parent_domain) plus base_path, from the container's own proxy block or
// the service's primary one. "" = not published. auth is the declared string; auth_type is the C3 tier derived from it.
function publicOf(c, b) {
  const p = c.proxy || (b.proxy && (b.proxy.primary || b.proxy)) || null;
  if (!p || typeof p !== "object") return { url: "", auth: "" };
  const host = p.domain || p.parent_domain || "";
  if (!host) return { url: "", auth: String(p.auth || "") };
  return { url: host + (p.base_path || ""), auth: String(p.auth || "") };
}
function authTier(url, auth) {
  if (!url) return "mesh";
  const a = auth.toLowerCase();
  if (a === "two_factor") return "woauth";
  if (a === "bearer") return "bearer";
  return "open";
}

export function derive(root) {
  const vocab = JSON.parse(fs.readFileSync(path.join(root, "_shared", "containers-taxonomy.json"), "utf8"));
  const items = loadServices(root).flatMap(entriesOf).map((e) => ({
    name: e.name, kind: e.kind, service: e.b.name, role: e.role, dir: e.dir,
    group: e.tax ? e.tax.group : null, category: e.tax ? e.tax.category : null,
    description: e.b.description || "",
    image: e.c.image || (e.b.docker ? `${e.b.docker.registry || ""}/${e.b.docker.image || ""}`.replace(/^\//, "") : ""),
    host: (e.b.deploy && e.b.deploy.host) || "",
    dns: e.c.dns || e.b.dns || "",
    port: e.c.port ?? e.b.port ?? null,
    public: e.c.public === true,
    protocol: e.c.protocol || "",
    db_engine: e.c.db_engine || "",
    legacy_category: e.b.category || "",
    ...(() => { const p = publicOf(e.c, e.b); return { public_url: p.url, auth: p.auth, auth_type: authTier(p.url, p.auth) }; })(),
  }));
  const containers = items.filter((i) => i.kind === "container");
  const artifacts = items.filter((i) => i.kind === "artifact");
  const groups = vocab.groups.map((g) => ({
    id: g.id, label: g.label,
    categories: g.categories.map((cat) => ({
      label: cat,
      containers: containers.filter((c) => c.group === g.label && c.category === cat).map((c) => c.name),
    })),
  }));
  return {
    _warning: "DO NOT EDIT - generated by the configs-sync engine from cloud-u-containers */build.json taxonomy",
    schema: "containers-declared/v1",
    groups, containers, artifacts,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const [root, out] = process.argv.slice(2);
  if (!root || !out) { console.error("usage: containers-declared.mjs <root> <out>"); process.exit(2); }
  fs.writeFileSync(out, JSON.stringify(derive(root), null, 2) + "\n");
  console.log("wrote", out);
}
