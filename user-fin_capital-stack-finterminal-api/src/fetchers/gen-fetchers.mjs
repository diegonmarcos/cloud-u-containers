#!/usr/bin/env node
// gen-fetchers.mjs — the capital-stack-finterminal-api fetch jobs, GENERATED from the FinTerm app's declarations (#1351, design 3.6).
//
//   node gen-fetchers.mjs [--android <cloudy-u-android checkout>] [--check]
//
// Reads (read-only) ad_Capital-Stack-FinTerminal/data/{sources,dashboards,central-banks,universe}.json from cloudy-u-android (a local checkout with
// --android or $CLOUD_U_ANDROID, else main through `gh api`). Every model panel that names the container's /v1 surface as its primary route
// is backed by the public routes it declares (its own source and its fallbacks): one job per route the container implements
// (CONTAINER_CONNECTORS, the same list as finterm/normalise.rs), its items merged, its cadence the source's schedule.ttl_s, its rate the
// source's rate_limit. universe.json (the market store: EOD history, yield matrix, GDP, FX, SEC earnings) is checked and embedded
// as declared['universe.json'], each `ref` source resolved to its sources.json endpoint. Writes ../code/fetchers.json (DO NOT EDIT); --check exits 1 when the committed file differs from a fresh render.
// No address is typed here or in the Rust: every endpoint, path and parameter comes from the app's declaration.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const OUT = join(HERE, '..', 'code', 'fetchers.json');
export const APP = 'ad_Capital-Stack-FinTerminal';
/** The connectors finterm/normalise.rs implements (the job list holds no other). */
export const CONTAINER_CONNECTORS = ['ff_calendar', 'declared_events', 'cboe_quotes', 'nyfed_rates', 'treasury_xml', 'frankfurter_rates', 'coinbase_exchange', 'polymarket_events', 'bls_series', 'sec_submissions', 'sec_concept'];
/** The store formats finterm/store.rs parses (STORE_FORMATS there; the two lists are the same set). */
export const STORE_FORMATS = ['cboe_chart', 'fred_csv', 'coinbase_candles', 'csv_long', 'csv_wide', 'valet', 'dbnomics'];
const HEADER = 'GENERATED by user-fin_capital-stack-finterminal-api/src/fetchers/gen-fetchers.mjs from cloudy-u-android ad_Capital-Stack-FinTerminal/data/{sources,dashboards,central-banks,universe}.json — DO NOT EDIT. Re-run: node src/fetchers/gen-fetchers.mjs';
const OPTS = ['labels', 'years', 'key_dim', 'last', 'scale', 'forms', 'cik', 'lookback_days', 'importance', 'each_days'];

/** Pure: the app's declarations -> the job list. Throws on a contradiction. */
export function buildFetchers({ sources, dashboards, centralBanks, universe, declarationSha }) {
  const fail = (m) => { throw new Error(m); };
  const byId = new Map(sources.sources.map((s) => [s.id, s]));
  const primary = sources.sources.find((s) => s.primary) ?? fail('no primary source');
  const v1 = primary.paths?.v1 ?? fail(`${primary.id} declares no paths.v1`);
  const jobs = new Map();
  for (const d of dashboards.dashboards) for (const p of d.panels) {
    const f = p.fetch;
    const api = f?.primary?.api;
    if (!f || f.primary?.source !== primary.id || !api) continue;
    if (!api.startsWith(v1 + '/')) fail(`${d.id}/${p.id}: ${api} is not under ${v1}`);
    // the store route (universe.json history.route) is backed by the market store, not by a per-run job
    if (api === universe?.history?.route) continue;
    const serves = api.replace(/\/[^/]*\^[^/]*\//, '/{symbol}/').replace(/^(\/v1\/quotes\/)[^/]+(\/history)$/, '$1{symbol}$2').replace(/^(\/v1\/fundamentals\/)[^/]+$/, '$1{symbol}').replace(/^(\/v1\/curves\/)[^/]+$/, (m) => m);
    const routes = [{ source: p.source, provider: f.provider, path: f.path, params: f.params, each: f.each, ...pick(f) }, ...(f.fallbacks ?? []).map((fb) => ({ ...pick(f), ...fb }))];
    for (const r of routes) {
      const s = byId.get(r.source) ?? fail(`${d.id}/${p.id}: unknown source ${r.source}`);
      const connector = r.provider ?? s.connector;
      if (!CONTAINER_CONNECTORS.includes(connector)) continue;
      if (s.auth?.type !== 'none') fail(`${d.id}/${p.id}: ${s.id} is keyed; a keyed source needs a secret, not a job`);
      const key = JSON.stringify([s.id, connector, r.path ?? '', r.params ?? {}]);
      const id = `${s.id}:${createHash('sha256').update(key).digest('hex').slice(0, 8)}`;
      const job = jobs.get(id) ?? {
        id, source: s.id, connector, endpoint: s.endpoint, path: r.path ?? '', params: r.params ?? {}, items: [],
        ttl_s: Math.max(60, s.schedule?.ttl_s ?? 3600), per_min: s.rate_limit?.per_min ?? null, per_day: s.rate_limit?.per_day ?? null,
        opts: {}, serves: [], paths: s.paths ?? {}, attribution: s.attribution ?? s.name,
      };
      for (const it of r.each ?? []) if (!job.items.includes(it)) job.items.push(it);
      for (const k of OPTS) if (r[k] !== undefined && job.opts[k] === undefined) job.opts[k] = r[k];
      if (!job.serves.includes(serves)) job.serves.push(serves);
      jobs.set(id, job);
    }
  }
  // a rate-limited source: its jobs together stay inside the declared per-minute / per-day budget
  for (const j of jobs.values()) {
    const calls = Math.max(1, j.items.length || (j.opts.each_days ?? 1));
    if (j.per_day && (86400 / j.ttl_s) * calls > j.per_day) fail(`${j.id}: ${calls} request(s) every ${j.ttl_s}s exceed ${j.source}'s ${j.per_day}/day`);
    if (j.per_min && calls > j.per_min) fail(`${j.id}: ${calls} requests per run exceed ${j.source}'s ${j.per_min}/min`);
  }
  const list = [...jobs.values()].sort((a, b) => a.id.localeCompare(b.id));
  const strip = (v) => Array.isArray(v) ? v.map(strip) : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).filter(([k]) => !k.startsWith('_')).map(([k, x]) => [k, strip(x)])) : v;
  return { _generated: HEADER, declaration_sha: declarationSha, v1, jobs: list, declared: { 'central-banks.json': strip(centralBanks), 'universe.json': buildUniverse(strip(universe ?? fail('universe.json missing')), byId, fail, dashboards, v1) } };
}

/** Pure: universe.json -> the store declaration, every `ref` source resolved to sources.json; throws on a contradiction. */
export function buildUniverse(u, byId, fail, dashboards, v1) {
  const src = {};
  for (const [id, s] of Object.entries(u.sources ?? fail('universe: no sources'))) {
    let r = { ...s };
    if (s.ref) {
      const d = byId.get(s.ref) ?? fail(`universe: source ${id} refers to unknown source ${s.ref}`);
      if (d.auth?.type !== 'none') fail(`universe: source ${id} (${s.ref}) is keyed`);
      r = { ...s, name: d.name, endpoint: d.endpoint, licence: d.licence ?? d.name, paths: d.paths ?? {} };
    } else if (s.auth !== 'none') fail(`universe: source ${id} is not declared key-free`);
    if (!/^https:\/\//.test(r.endpoint ?? '')) fail(`universe: source ${id} has no https endpoint`);
    if (!(r.per_min > 0 && r.per_min <= 60)) fail(`universe: source ${id} needs a per_min budget in 1..60`);
    if (r.format && !STORE_FORMATS.includes(r.format)) fail(`universe: source ${id} format ${r.format} has no store parser`);
    src[id] = r;
  }
  const h = u.history ?? fail('universe: no history');
  if (!(h.years >= 10)) fail('universe: history keeps fewer than 10 years');
  if (h.route !== v1 + '/history') fail(`universe: history.route ${h.route} is not ${v1}/history`);
  const symbols = historySymbols(dashboards, h, fail);
  for (const s of symbols) {
    if (s.source === null) { if (!s.reason) fail(`universe: ${s.symbol} is unavailable without a reason`); continue; }
    if (s.source === 'computed') { if (!u.em_bonds?.ccy?.[s.country]) fail(`universe: computed ${s.symbol} names no EM currency`); continue; }
    const so = src[s.source] ?? fail(`universe: ${s.symbol} names unknown source ${s.source}`);
    if (!so.format) fail(`universe: ${s.symbol} source ${s.source} has no history format`);
    if (s.kind === 'etf_proxy' && !s.proxy) fail(`universe: ${s.symbol} is a proxy that names no proxy`);
  }
  const c = u.curves ?? fail('universe: no curves');
  const countries = new Set([...c.dm, ...c.reference, ...c.em_candidates]);
  const fids = new Set();
  for (const f of c.feeds) {
    if (fids.has(f.id)) fail(`universe: curve feed ${f.id} declared twice`);
    fids.add(f.id);
    src[f.source] ?? fail(`universe: curve feed ${f.id} names unknown source ${f.source}`);
    if (!STORE_FORMATS.includes(f.format)) fail(`universe: curve feed ${f.id} format ${f.format} has no store parser`);
    for (const out of Object.values(f.map)) {
      const [k, cc, ten] = out.split(':');
      if (k !== 'curve' || !countries.has(cc) || !c.tenors.includes(ten)) fail(`universe: curve feed ${f.id} maps to ${out}, not a declared country x tenor`);
    }
    if (!f.method) fail(`universe: curve feed ${f.id} documents no method`);
  }
  for (const k of ['gdp']) src[c[k].source] ?? fail(`universe: curves.${k} names unknown source`);
  src[u.em_bonds.fx.source] ?? fail('universe: em_bonds.fx names unknown source');
  src[u.earnings.source] ?? fail('universe: earnings names unknown source');
  for (const [t, cik] of Object.entries(u.earnings.companies)) if (!/^\d{10}$/.test(cik)) fail(`universe: earnings ${t} CIK ${cik} is not 10 digits`);
  const { resolve: _r, unavailable: _u, extra: _e, ...hist } = h;
  return { ...u, sources: src, history: { ...hist, symbols } };
}

/** Pure: every symbol the APK tables read on the store route, resolved (universe.json history.resolve, the panel's symbol_map, a plain
 * Cboe ticker, a Coinbase pair) or declared unavailable; then history.extra. A table symbol none of these covers is a contradiction. */
export function historySymbols(dashboards, h, fail) {
  const out = new Map();
  for (const d of dashboards.dashboards) for (const p of d.panels) {
    const f = p.fetch;
    if (f?.primary?.api !== h.route) continue;
    for (const s of f.each ?? []) {
      const table = `${d.id}/${p.id}`;
      if (out.has(s)) { out.get(s).tables.push(table); continue; }
      const m = f.symbol_map?.[s];
      let e;
      if (h.resolve?.[s]) e = { ...h.resolve[s] };
      else if (h.unavailable?.[s]) e = { source: null, kind: 'unavailable', reason: h.unavailable[s] };
      else if (m) e = m === s ? { source: 'cboe', code: m, kind: 'etf' } : m.startsWith('_') ? { source: 'cboe', code: m, kind: 'index' } : { source: 'cboe', code: m, kind: 'etf_proxy', proxy: m };
      else if (p.source === 'coinbase' && /^[A-Z]{2,6}-[A-Z]{3,4}$/.test(s)) e = { source: 'coinbase', code: s, kind: 'spot' };
      else if (p.source === 'cboe' && /^[A-Z]{1,5}$/.test(s)) e = { source: 'cboe', code: s, kind: 'etf' };
      else fail(`universe: the APK table ${table} reads ${s} on ${h.route}, which universe.json neither resolves nor declares unavailable`);
      out.set(s, { symbol: s, name: f.labels?.[s] ?? s, ...e, tables: [table] });
    }
  }
  for (const x of h.extra ?? []) if (!out.has(x.symbol)) out.set(x.symbol, { ...x, tables: [] });
  return [...out.values()];
}
const pick = (f) => Object.fromEntries(OPTS.filter((k) => f[k] !== undefined).map((k) => [k, f[k]]));

function readAndroid(rel, local) {
  if (local) return readFileSync(join(local, rel), 'utf8');
  return execFileSync('gh', ['api', '-H', 'Accept: application/vnd.github.raw', `repos/diegonmarcos/cloudy-u-android/contents/${rel}?ref=main`], { maxBuffer: 64 * 1024 * 1024 }).toString('utf8');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const a = process.argv.slice(2);
  const li = a.indexOf('--android');
  const local = li >= 0 ? resolve(a[li + 1]) : process.env.CLOUD_U_ANDROID || '';
  const texts = ['sources', 'dashboards', 'central-banks', 'universe'].map((n) => readAndroid(`${APP}/data/${n}.json`, local));
  const sha = createHash('sha256').update(texts.join('\n')).digest('hex');
  let doc;
  try {
    doc = buildFetchers({ sources: JSON.parse(texts[0]), dashboards: JSON.parse(texts[1]), centralBanks: JSON.parse(texts[2]), universe: JSON.parse(texts[3]), declarationSha: sha });
  } catch (e) { console.error('FAIL', e.message); process.exit(1); }
  const text = JSON.stringify(doc, null, 2) + '\n';
  if (a.includes('--check')) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error(`FAIL drift: ${OUT} differs from a fresh render; run node src/fetchers/gen-fetchers.mjs`); process.exit(1); }
    console.log(`gen-fetchers: up to date (${doc.jobs.length} jobs)`);
  } else {
    writeFileSync(OUT, text);
    console.log(`gen-fetchers: ${doc.jobs.length} jobs -> ${OUT}`);
  }
}
